-- CastraMóvel: tabelas + travas de segurança. Rode no Supabase: SQL Editor > New query > Run.
-- Os dados pessoais já chegam aqui criptografados pelo app (colunas "text" com prefixo v1:).

create table if not exists public.usuario (
    id integer generated by default as identity primary key,
    nome varchar(50) not null unique,
    senha_hash varchar(255) not null,
    email text  -- criptografado pelo app; identifica a conta correspondente no Supabase Auth
);

-- Se você já tinha rodado uma versão anterior deste arquivo, esta linha acrescenta a coluna de e-mail:
alter table public.usuario add column if not exists email text;

-- Perfil de acesso: 'admin' vê o sistema todo; 'campo' (equipe no local) só vê a tela Atendimento.
-- Quem já existe fica 'admin'. Contas novas criadas pelo app entram como 'campo'.
-- Para promover alguém:  python usuarios.py perfil EMAIL admin
alter table public.usuario add column if not exists perfil varchar(20) not null default 'admin';

create table if not exists public.tutor (
    id integer generated by default as identity primary key,
    nome_completo text not null,
    telefone text not null,
    cpf text not null,
    cpf_idx varchar(64) not null unique,
    endereco text not null,
    numero text not null
);

create table if not exists public.animal (
    id integer generated by default as identity primary key,
    nome text not null,
    especie text,
    raca text not null,
    sexo text not null,
    microchip text,
    microchip_idx varchar(64) unique,
    tutor_id integer not null references public.tutor(id)
);

-- Compatibilidade com tabelas animal criadas por versões anteriores.
alter table public.animal add column if not exists especie text;

create table if not exists public.documento (
    id integer generated by default as identity primary key,
    nome_arquivo text not null,
    caminho varchar(200) not null,
    conteudo bytea,  -- arquivo já cifrado pelo app; assim os anexos não dependem do disco do servidor
    tutor_id integer not null references public.tutor(id)
);

-- Se a tabela documento já existia, esta linha acrescenta a coluna do conteúdo:
alter table public.documento add column if not exists conteudo bytea;

create table if not exists public.agendamento (
    id integer generated by default as identity primary key,
    data date not null,
    hora time not null,
    animal_id integer not null references public.animal(id),
    presente boolean  -- null = aguardando, true = compareceu, false = faltou
);

-- Se a tabela agendamento já existia, esta linha acrescenta a coluna de presença:
alter table public.agendamento add column if not exists presente boolean;

-- IMPORTANTE: a versão anterior só permitia 1 animal por data/hora. Agora cada horário tem várias vagas
-- (limites em agenda_regras.py, conferidos pelo app). Esta linha remove a trava antiga; sem ela,
-- o segundo animal do mesmo horário seria recusado pelo banco.
alter table public.agendamento drop constraint if exists uq_agendamento_data_hora;
create index if not exists idx_agendamento_data on public.agendamento (data);

-- ---------------------------------------------------------------------------
-- TRAVA: ninguém acessa pelas chaves públicas (publishable/anon) do Supabase.
-- RLS ligado e NENHUMA policy = a API pública não enxerga nem altera nada.
-- O app conecta direto no Postgres com a senha do banco, que não passa pela API pública.
-- ---------------------------------------------------------------------------
alter table public.usuario     enable row level security;
alter table public.tutor       enable row level security;
alter table public.animal      enable row level security;
alter table public.documento   enable row level security;
alter table public.agendamento enable row level security;

revoke all on all tables    in schema public from anon, authenticated;
revoke all on all sequences in schema public from anon, authenticated;
revoke all on all functions in schema public from anon, authenticated;
alter default privileges in schema public revoke all on tables    from anon, authenticated;
alter default privileges in schema public revoke all on sequences from anon, authenticated;

-- Conferência: todas as linhas abaixo devem mostrar rls_ativo = true.
select c.relname as tabela, c.relrowsecurity as rls_ativo
from pg_class c join pg_namespace n on n.oid = c.relnamespace
where n.nspname = 'public' and c.relkind = 'r'
order by c.relname;
